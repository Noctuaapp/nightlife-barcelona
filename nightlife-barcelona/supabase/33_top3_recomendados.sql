-- Noctua · Top 3 recomendado por Noctua en la portada · 25/10/2026
-- Ejecutar entero en Supabase › SQL Editor. Se puede repetir sin problema.
--
-- "Poner en la página principal por noche o semana un top 3 de clubs recomendados por Noctua.
-- Que solo aparezca cuando pongamos alguno nosotros." Se gestiona en Admin › Top 3 de Noctua.
--   period = 'night' → una noche concreta (starts_on = ends_on = esa fecha)
--   period = 'week'  → de lunes a domingo
-- La portada enseña el de esta noche si hay; si no, el de la semana; si no hay ninguno, nada.
-- =====================================================================================

create table if not exists public.noctua_picks (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.clubs(id) on delete cascade,
  rank smallint not null check (rank between 1 and 3),
  period text not null check (period in ('night', 'week')),
  starts_on date not null,
  ends_on date not null,
  note text,
  created_at timestamptz not null default now(),
  check (ends_on >= starts_on)
);

create index if not exists noctua_picks_dates_idx on public.noctua_picks (starts_on, ends_on);

alter table public.noctua_picks enable row level security;

drop policy if exists "Top 3: lectura pública" on public.noctua_picks;
create policy "Top 3: lectura pública" on public.noctua_picks
for select using (true);

drop policy if exists "Top 3: solo admin escribe" on public.noctua_picks;
create policy "Top 3: solo admin escribe" on public.noctua_picks
for all to authenticated
using (public.is_noctua_admin())
with check (public.is_noctua_admin());

select 'Tabla del Top 3 lista' as resultado;
