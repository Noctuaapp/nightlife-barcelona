-- Ejecutar entero en Supabase › SQL Editor. Se puede repetir sin problema.
--
-- 1) REGISTRO DE CAMBIOS: ahora que los dueños editan su ficha desde la propia página, hace falta
--    saber quién cambió qué y cuándo (como cualquier panel serio: Shopify, Stripe...). Cada vez que
--    una PERSONA (tú o un dueño/organizador con sesión) crea, cambia o borra un club, evento,
--    noche, sesión, esencial, entrada o top 3, se guarda: cuándo, quién, qué ficha y qué campos
--    pasaron de qué valor a cuál. Lo que hacen las tareas automáticas (fotos y datos de Google
--    cada noche) NO se guarda: serían miles de líneas de ruido.
--    Solo lo ve el admin (Admin › Registro de cambios). Se borra solo lo de más de 13 meses.
--
-- 2) ESTADO DEL SISTEMA: un resumen para Ajustes y herramientas — tamaño de la base de datos y de
--    las fotos (con los límites del plan gratuito de Supabase), llamadas de pago a Google por día,
--    y cuándo se ejecutaron por última vez las tareas automáticas.
-- =====================================================================================

-- 1) Registro de cambios ---------------------------------------------------------------
create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  table_name text not null,
  row_id text,
  row_name text,
  action text not null check (action in ('crear', 'cambiar', 'borrar')),
  user_id uuid,
  user_email text,
  changes jsonb
);
create index if not exists admin_audit_log_at_idx on public.admin_audit_log (at desc);
create index if not exists admin_audit_log_row_idx on public.admin_audit_log (table_name, row_id);

alter table public.admin_audit_log enable row level security;
drop policy if exists "Registro: solo admin lee" on public.admin_audit_log;
create policy "Registro: solo admin lee" on public.admin_audit_log
for select to authenticated using (public.is_noctua_admin());
-- Nadie escribe a mano: solo el trigger (que corre con permisos propios).

create or replace function public.noctua_audit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  v_old jsonb := case when tg_op <> 'INSERT' then to_jsonb(old) end;
  v_new jsonb := case when tg_op <> 'DELETE' then to_jsonb(new) end;
  v_changes jsonb;
  v_row jsonb := coalesce(v_new, v_old);
begin
  -- Solo personas con sesión. Las tareas automáticas (service role) no tienen auth.uid().
  if uid is null then
    return coalesce(new, old);
  end if;

  if tg_op = 'UPDATE' then
    select jsonb_object_agg(key, jsonb_build_object('antes', v_old -> key, 'despues', value))
      into v_changes
    from jsonb_each(v_new)
    where (v_old -> key) is distinct from value
      and key not in ('updated_at', 'live_status_updated_at')
      and key not like 'google\_%';
    if v_changes is null then
      return new; -- no ha cambiado nada que importe
    end if;
  elsif tg_op = 'INSERT' then
    select jsonb_object_agg(key, value) into v_changes from jsonb_each(v_new) where value <> 'null'::jsonb;
  else
    v_changes := v_old;
  end if;

  insert into public.admin_audit_log (table_name, row_id, row_name, action, user_id, user_email, changes)
  values (
    tg_table_name,
    v_row ->> 'id',
    left(coalesce(v_row ->> 'name', v_row ->> 'title', v_row ->> 'club_name'), 140),
    case tg_op when 'INSERT' then 'crear' when 'UPDATE' then 'cambiar' else 'borrar' end,
    uid,
    (select email from auth.users where id = uid),
    v_changes
  );
  return coalesce(new, old);
exception when others then
  -- El registro nunca debe impedir guardar un cambio.
  return coalesce(new, old);
end $$;

do $$
declare
  t text;
begin
  foreach t in array array['clubs', 'events', 'club_events', 'club_sessions', 'event_sessions', 'essentials', 'tickets', 'noctua_picks'] loop
    if to_regclass('public.' || t) is not null then
      execute format('drop trigger if exists noctua_audit_trg on public.%I', t);
      execute format('create trigger noctua_audit_trg after insert or update or delete on public.%I for each row execute function public.noctua_audit()', t);
    end if;
  end loop;
end $$;

-- Limpieza: lo de más de 13 meses (se llama desde el estado del sistema, ver abajo).
create or replace function public.noctua_purge_audit()
returns void language sql security definer set search_path = public as $$
  delete from public.admin_audit_log where at < now() - interval '13 months';
$$;

-- 2) Estado del sistema -------------------------------------------------------------------
create or replace function public.admin_system_status()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  result jsonb := '{}'::jsonb;
  v jsonb;
  t text;
begin
  if not public.is_noctua_admin() then
    raise exception 'solo admin';
  end if;

  perform public.noctua_purge_audit();

  result := result || jsonb_build_object('db_mb', round(pg_database_size(current_database()) / 1048576.0, 1));

  -- Fotos por carpeta (bucket): número y tamaño.
  begin
    select coalesce(jsonb_agg(jsonb_build_object('bucket', bucket_id, 'files', n, 'mb', mb) order by mb desc), '[]'::jsonb)
      into v
    from (
      select bucket_id, count(*) as n, round(coalesce(sum((metadata ->> 'size')::bigint), 0) / 1048576.0, 1) as mb
      from storage.objects group by bucket_id
    ) s;
    result := result || jsonb_build_object('storage', v);
  exception when others then
    result := result || jsonb_build_object('storage', '[]'::jsonb);
  end;

  -- Llamadas de pago a Google, últimos 14 días.
  begin
    select coalesce(jsonb_agg(jsonb_build_object('day', day, 'calls', calls_used) order by day), '[]'::jsonb)
      into v
    from public.api_call_budget where day >= current_date - 13;
    result := result || jsonb_build_object('google_calls', v);
  exception when others then
    result := result || jsonb_build_object('google_calls', '[]'::jsonb);
  end;

  -- Última vez que la tarea nocturna de Google actualizó algo en cada tabla.
  foreach t in array array['clubs', 'events', 'essentials'] loop
    begin
      execute format('select to_jsonb(max(google_last_refreshed_at)) from public.%I', t) into v;
      result := result || jsonb_build_object('last_google_' || t, v);
    exception when others then
      result := result || jsonb_build_object('last_google_' || t, null);
    end;
  end loop;

  -- Cifras generales.
  result := result || jsonb_build_object(
    'users', (select count(*) from auth.users),
    'users_7d', (select count(*) from auth.users where created_at > now() - interval '7 days'),
    'clubs_visible', (select count(*) from public.clubs where coalesce(hidden, false) = false),
    'clubs_hidden', (select count(*) from public.clubs where coalesce(hidden, false) = true),
    'clubs_owned', (select count(*) from public.clubs where owner_user_id is not null),
    'audit_7d', (select count(*) from public.admin_audit_log where at > now() - interval '7 days')
  );

  begin
    select jsonb_build_object('analytics_rows', count(*), 'analytics_oldest', min(created_at)) into v from public.analytics;
    result := result || v;
  exception when others then
    null;
  end;

  return result;
end $$;

revoke all on function public.admin_system_status() from public, anon;
grant execute on function public.admin_system_status() to authenticated;

select 'Registro de cambios y estado del sistema listos' as resultado;
