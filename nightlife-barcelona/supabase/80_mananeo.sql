-- =====================================================================================
-- Noctua · Mañaneo / resaca (sitios de afterhour) · 05/11/2026
-- Ejecutar entero en Supabase › SQL Editor. Se puede repetir sin problema.
--
-- «Poner un apartado de mañaneo o de resaca para añadir sitios de afterhour en eventos, pero
-- oculto a todos los usuarios de momento hasta que terminemos la edición nosotros.»
--
-- Los sitios se añaden en Admin › Mañaneo. Están OCULTOS por defecto (hidden = true):
--   · Mientras MANANEO_HIDDEN valga true en src/lib/featureFlags.ts, el apartado solo lo ve el admin
--     dentro de Eventos, y los visitantes no lo reciben ni siquiera por la API (la lectura pública
--     de abajo solo devuelve filas con hidden = false).
--   · Cuando esté listo: pon MANANEO_HIDDEN = false en el código y, en Admin › Mañaneo, deja visibles
--     (hidden = false) los sitios que quieras enseñar.
-- =====================================================================================

create table if not exists public.mananeo_places (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) > 0),
  description text,
  neighborhood text,
  address text,
  latitude double precision,
  longitude double precision,
  hours text,          -- «06:00-14:00» o «S/D 06:00-14:00»; varias franjas separadas por coma
  music text,
  price text,
  image text,
  instagram text,
  website text,
  hidden boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.mananeo_places enable row level security;

drop policy if exists "Mañaneo: lectura pública de los visibles" on public.mananeo_places;
create policy "Mañaneo: lectura pública de los visibles" on public.mananeo_places
for select using (hidden = false);

drop policy if exists "Mañaneo: el admin lo ve todo" on public.mananeo_places;
create policy "Mañaneo: el admin lo ve todo" on public.mananeo_places
for select to authenticated using (public.is_noctua_admin());

drop policy if exists "Mañaneo: solo admin escribe" on public.mananeo_places;
create policy "Mañaneo: solo admin escribe" on public.mananeo_places
for all to authenticated
using (public.is_noctua_admin())
with check (public.is_noctua_admin());

select 'Tabla de Mañaneo lista (todo oculto hasta que lo publiques)' as resultado;
