-- 61 · Recorrido de cada línea de Nitbus, parada a parada y en orden (31/10/2026).
--
-- Para qué: la página /nitbus/N24 enseña el esquema de la línea (cabecera → paradas → cabecera).
-- Hasta ahora las paradas estaban sueltas en `essentials` y sin orden. La importación de
-- OpenStreetMap (Admin › Ajustes y herramientas › Paradas de Nitbus) rellena esta tabla con el
-- orden del recorrido de cada línea y cada sentido.
--
-- Seguro de ejecutar más de una vez. Sin esta tabla la web sigue funcionando: enseña las paradas
-- de cada línea por orden alfabético y avisa de que falta el orden.

create table if not exists public.nitbus_line_stops (
  id bigint generated by default as identity primary key,
  line text not null,                       -- 'N24'
  direction smallint not null default 0,    -- 0 = un sentido, 1 = el contrario
  seq integer not null,                     -- posición en el recorrido (1, 2, 3...)
  name text not null,
  code text,
  latitude double precision,
  longitude double precision,
  created_at timestamptz not null default now()
);

create index if not exists nitbus_line_stops_line_idx
  on public.nitbus_line_stops (line, direction, seq);

alter table public.nitbus_line_stops enable row level security;

-- Cualquiera puede leerla (son datos públicos del transporte); solo escribe la importación del
-- admin, que usa la clave de servicio y se salta estas reglas.
drop policy if exists "nitbus_line_stops_public_read" on public.nitbus_line_stops;
create policy "nitbus_line_stops_public_read"
  on public.nitbus_line_stops for select
  to anon, authenticated
  using (true);

revoke all on public.nitbus_line_stops from anon, authenticated;
grant select on public.nitbus_line_stops to anon, authenticated;

-- Comprobación: debe salir la tabla con RLS activado.
select tablename, rowsecurity as rls_activado
from pg_tables
where schemaname = 'public' and tablename = 'nitbus_line_stops';
